// tabs/earnings-drill.js — the earnings drill panel.
//
// Split out of earnings-hub.js for the same reason the technicals drill was: it is opened
// from several places (all three sub-views, plus the scatter on Quality & Growth), and
// keeping it separate stops those modules importing each other in a circle.
//
// Structure, top to bottom:
//   · the 8-quarter mini table (revenue / OPM / PAT / EPS) with a sparkline per row
//   · the segment split as a share bar
//   · the 15 rules grouped into their five categories, each with a status pill, the measured
//     value, the note, a points badge and the Source · Calculation · Implementation chips

import { openDrill } from '../ui/screener.js';
import { escapeHtml } from '../core/dom.js';
import { META } from '../scoring/rule-meta.js';
import { spark } from '../ui/components.js';
import { meta as earningsMeta } from '../data/earnings.js';

const CATEGORY_ORDER = ['Growth', 'Margins', 'Earnings Quality', 'Surprise', 'Consistency'];

const ICON_LINK = `<svg class="h-3 w-3 flex-shrink-0" fill="none" stroke="currentColor" stroke-width="2" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" d="M10 6H6a2 2 0 0 0-2 2v10a2 2 0 0 0 2 2h10a2 2 0 0 0 2-2v-4M14 4h6m0 0v6m0-6L10 14"/></svg>`;
const ICON_CALC = `<svg class="h-3 w-3 flex-shrink-0" fill="none" stroke="currentColor" stroke-width="2" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" d="M9 7h6m-6 4h6m-3 4h3M7 21h10a2 2 0 0 0 2-2V5a2 2 0 0 0-2-2H7a2 2 0 0 0-2 2v14a2 2 0 0 0 2 2z"/></svg>`;
const ICON_LOGIC = `<svg class="h-3 w-3 flex-shrink-0" fill="none" stroke="currentColor" stroke-width="2" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" d="M9 12h6m-6 4h6m2 5H7a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h5.586a1 1 0 0 1 .707.293l5.414 5.414a1 1 0 0 1 .293.707V19a2 2 0 0 1-2 2z"/></svg>`;

/**
 * The synthetic-data marker, rendered immediately above the figures in every drill.
 *
 * Keyed off `meta().isMock`, which is derived from the payload's own `source` field — so
 * swapping in the real filings feed removes this strip with no code change here, and no
 * amount of editing this file can leave a synthetic number unlabelled while the feed is mock.
 */
function provenanceStripHtml() {
  if (!earningsMeta()?.isMock) return '';
  return `
    <div class="mb-5 rounded-xl bg-amber-50 p-3 ring-1 ring-amber-200">
      <div class="text-[11px] font-bold uppercase tracking-wider text-amber-700">Illustrative figures</div>
      <div class="mt-1 text-[11px] leading-relaxed text-amber-800">
        Company name, ticker and sector are real. Every financial number below is synthetic, generated by
        <code class="rounded bg-amber-100 px-1">scripts/gen-mock-earnings.mjs</code> — not a reported figure.
      </div>
    </div>`;
}

// Points may be fractional (tax rate 0.5, revenue surprise 0.5).
export function fmtPoints(n) {
  if (n == null) return '—';
  return Number.isInteger(n) ? String(n) : n.toFixed(1);
}

const crore = (n) => (n == null ? '—' : `₹${Math.round(n).toLocaleString('en-IN')}`);
const pct = (n, d = 1) => (n == null ? '—' : `${n.toFixed(d)}%`);

// The three provenance chips. Implementation turns amber where our logic deviates from the
// client's stated rule (rule-meta `ourLogic` non-null).
function metaChips(ruleKey, company) {
  const rule = META.earnings?.[ruleKey];
  if (!rule) return '';
  const src = typeof rule.source === 'function' ? rule.source(company || {}) : rule.source;
  const deviates = !!rule.ourLogic;
  const chip = (inner, cls) => `<span class="inline-flex items-center gap-1 rounded-md px-1.5 py-0.5 text-[10px] font-semibold ${cls}">${inner}</span>`;

  return `
    <div class="mt-2 flex flex-wrap items-center gap-1.5 border-t border-slate-100 pt-2">
      ${
        src?.url
          ? `<a href="${escapeHtml(src.url)}" target="_blank" rel="noopener" data-stop title="${escapeHtml(src.section || '')}"
               class="inline-flex items-center gap-1 rounded-md bg-slate-100 px-1.5 py-0.5 text-[10px] font-semibold text-slate-600 transition-colors hover:bg-indigo-50 hover:text-indigo-700">
               ${ICON_LINK}<span>${escapeHtml(src.label || 'Source')}</span></a>`
          : ''
      }
      ${
        rule.calculation
          ? `<details class="meta-details inline-block">
               <summary class="cursor-pointer list-none">${chip(`${ICON_CALC}<span>Calculation</span>`, 'bg-slate-100 text-slate-600 hover:bg-slate-200')}</summary>
               <div class="mt-1.5 rounded-lg bg-slate-50 p-2 text-[11px] leading-relaxed text-slate-600 ring-1 ring-slate-100">${escapeHtml(rule.calculation)}</div>
             </details>`
          : ''
      }
      <details class="meta-details inline-block">
        <summary class="cursor-pointer list-none">${chip(
          `${ICON_LOGIC}<span>Implementation</span>`,
          deviates ? 'bg-amber-100 text-amber-800 hover:bg-amber-200' : 'bg-slate-100 text-slate-600 hover:bg-slate-200'
        )}</summary>
        <div class="mt-1.5 space-y-1.5 rounded-lg bg-slate-50 p-2 text-[11px] leading-relaxed ring-1 ring-slate-100">
          <div><span class="font-bold text-slate-700">Client logic:</span> <span class="text-slate-600">${escapeHtml(rule.clientLogic)}</span></div>
          ${
            deviates
              ? `<div><span class="font-bold text-amber-800">Our implementation differs:</span> <span class="text-amber-800">${escapeHtml(rule.ourLogic)}</span></div>`
              : '<div class="text-slate-500">Implemented exactly as specified.</div>'
          }
        </div>
      </details>
    </div>`;
}

// 8-quarter mini table. One row per metric, a sparkline beside the label, then the values.
function quarterTableHtml(quarters) {
  if (!Array.isArray(quarters) || !quarters.length) return '';
  const rows = [
    { label: 'Revenue', get: (q) => q.revenue, fmt: crore, tone: 'brand' },
    { label: 'OPM', get: (q) => q.opm, fmt: (v) => pct(v), tone: 'positive' },
    { label: 'PAT', get: (q) => q.netProfit, fmt: crore, tone: 'accent' },
    { label: 'EPS', get: (q) => q.eps, fmt: (v) => (v == null ? '—' : `₹${v.toFixed(2)}`), tone: 'neutral' },
  ];
  return `
    <div class="mb-5">
      <div class="mb-2 text-xs font-bold uppercase tracking-wider text-slate-500">Eight-quarter series</div>
      <div class="table-scroll-surface scrollbar-thin overflow-x-auto rounded-xl ring-1 ring-slate-100" tabindex="0" role="region" aria-label="Eight-quarter earnings table">
        <table class="w-full text-[11px]">
          <thead class="bg-slate-50/70">
            <tr>
              <th scope="col" class="whitespace-nowrap px-2 py-1.5 text-left font-bold uppercase tracking-wide text-slate-500">Metric</th>
              <th scope="col" class="px-2 py-1.5 text-left font-bold uppercase tracking-wide text-slate-500">Trend</th>
              ${quarters.map((q) => `<th scope="col" class="whitespace-nowrap px-2 py-1.5 text-right font-bold text-slate-500">${escapeHtml(q.quarter)}</th>`).join('')}
            </tr>
          </thead>
          <tbody>
            ${rows
              .map((r) => {
                const values = quarters.map((q) => r.get(q));
                const clean = values.filter((v) => v != null);
                return `
                  <tr class="border-t border-slate-100">
                    <td class="whitespace-nowrap px-2 py-1.5 font-semibold text-slate-700">${r.label}</td>
                    <td class="px-2 py-1">${clean.length > 1 ? spark({ values: clean, width: 56, height: 18, tone: r.tone }) : ''}</td>
                    ${values
                      .map((v, i) => {
                        const isLast = i === values.length - 1;
                        const neg = typeof v === 'number' && v < 0;
                        return `<td class="whitespace-nowrap px-2 py-1.5 text-right tabular-nums ${isLast ? 'font-bold text-slate-900' : 'text-slate-600'} ${neg ? 'text-rose-600' : ''}">${r.fmt(v)}</td>`;
                      })
                      .join('')}
                  </tr>`;
              })
              .join('')}
          </tbody>
        </table>
      </div>
    </div>`;
}

// Segment split as a single stacked share bar plus a legend.
const SEGMENT_COLOURS = ['bg-indigo-500', 'bg-purple-500', 'bg-pink-500', 'bg-sky-500', 'bg-teal-500'];
function segmentHtml(segments) {
  if (!Array.isArray(segments) || !segments.length) return '';
  return `
    <div class="mb-5">
      <div class="mb-2 text-xs font-bold uppercase tracking-wider text-slate-500">Revenue by segment</div>
      <div class="flex h-3 w-full overflow-hidden rounded-full bg-slate-100">
        ${segments
          .map((s, i) => `<div class="${SEGMENT_COLOURS[i % SEGMENT_COLOURS.length]}" style="width:${Math.max(0, s.share)}%" title="${escapeHtml(s.name)}: ${s.share}%"></div>`)
          .join('')}
      </div>
      <div class="mt-2 grid grid-cols-2 gap-x-3 gap-y-1">
        ${segments
          .map(
            (s, i) => `
          <div class="flex items-center gap-1.5 text-[11px]">
            <span class="h-2 w-2 flex-shrink-0 rounded-full ${SEGMENT_COLOURS[i % SEGMENT_COLOURS.length]}"></span>
            <span class="min-w-0 flex-1 truncate text-slate-600">${escapeHtml(s.name)}</span>
            <span class="flex-shrink-0 font-semibold tabular-nums text-slate-700">${s.share}%</span>
          </div>`
          )
          .join('')}
      </div>
    </div>`;
}

/** Open the earnings drill for a scored row from data/earnings.js. */
export function openEarningsDrill(scored) {
  if (!scored) return;
  const c = scored.company || {};

  if (scored.tickerError) {
    openDrill({
      name: c.name || c.ticker || 'Unknown',
      sub: c.ticker || '',
      headerStats: [
        { label: 'Result Quality Score', value: 'No data', tone: 'neutral' },
        { label: 'Status', value: 'Not covered', tone: 'caution' },
      ],
      banner: {
        tone: 'slate',
        title: 'No result data for this company',
        body: `${scored.tickerError}. Nothing is estimated in its place — the row scores zero of zero and sorts last rather than disappearing from the view.`,
      },
      groups: [],
    });
    return;
  }

  const q = Array.isArray(c.quarters) && c.quarters.length ? c.quarters.at(-1) : null;
  const yearAgo = Array.isArray(c.quarters) && c.quarters.length >= 5 ? c.quarters.at(-5) : null;
  const revYoY = q && yearAgo && yearAgo.revenue ? ((q.revenue - yearAgo.revenue) / Math.abs(yearAgo.revenue)) * 100 : null;
  const epsEst = c.consensus?.eps;
  const surprise = q && epsEst ? ((q.eps - epsEst) / Math.abs(epsEst)) * 100 : null;

  // Group the breakdown into the model's five categories, with per-category subtotals.
  const byCategory = new Map();
  for (const b of scored.breakdown) {
    if (!byCategory.has(b.category)) byCategory.set(b.category, []);
    byCategory.get(b.category).push(b);
  }
  const ordered = [
    ...CATEGORY_ORDER.filter((cat) => byCategory.has(cat)),
    ...[...byCategory.keys()].filter((cat) => !CATEGORY_ORDER.includes(cat)),
  ];

  const groups = ordered.map((category) => {
    const items = byCategory.get(category);
    const catPoints = items.reduce((s, b) => s + b.points, 0);
    const catMax = items.reduce((s, b) => s + b.max, 0);
    return {
      category: `${category} · ${fmtPoints(catPoints)}/${catMax}`,
      items: items.map((b) => ({
        label: b.label,
        criteria: b.criteria,
        status: b.status,
        value: b.value || '',
        note: b.note,
        points: fmtPoints(b.points),
        max: b.max,
        extraHtml: metaChips(b.key, c),
      })),
    };
  });

  openDrill({
    name: c.name || c.ticker,
    sub: [c.ticker, c.sector, c.quarter].filter(Boolean).join(' · '),
    link: c.screenerUrl || null,
    linkLabel: 'View on Screener.in ↗',
    headerStats: [
      {
        label: 'Result Quality Score',
        value: `${fmtPoints(scored.totalPoints)}/${scored.totalMax}`,
        caption: `${scored.scorePct}%${scored.naCount ? ` · ${scored.naCount} n/a` : ''}`,
        tone: scored.hardFails.length ? 'negative' : scored.scorePct >= 60 ? 'positive' : scored.scorePct >= 40 ? 'caution' : 'negative',
      },
      {
        label: 'EPS Surprise',
        value: surprise == null ? '—' : `${surprise > 0 ? '+' : ''}${surprise.toFixed(1)}%`,
        caption: q && epsEst ? `₹${q.eps.toFixed(2)} vs ₹${epsEst.toFixed(2)} street` : '',
        tone: surprise == null ? 'neutral' : surprise > 1 ? 'positive' : surprise < -1 ? 'negative' : 'caution',
      },
    ],
    // The banner slot is reserved for the red flag. The provenance marker is NOT put here:
    // a loss-making company would then lose it, which is exactly the row whose numbers most
    // need the caveat. It renders as its own strip directly above the figures instead, so
    // every drill carries it regardless of what else the row is flagged for.
    banner: scored.hardFails.length
      ? {
          tone: 'rose',
          title: `Red flag: ${scored.hardFails.join(', ')}`,
          body: 'A loss-making quarter fails the quality screen outright. The remaining rules still score so you can see what is working underneath.',
        }
      : null,
    // Series and segments sit above the rules: the numbers first, then the verdicts on them.
    beforeGroupsHtml: `${provenanceStripHtml()}${quarterTableHtml(c.quarters)}${segmentHtml(c.segments)}${
      revYoY != null
        ? `<div class="mb-5 rounded-xl bg-slate-50 p-3 text-[11px] leading-relaxed text-slate-600 ring-1 ring-slate-100">
             Latest quarter <span class="font-semibold text-slate-800">${escapeHtml(c.quarter || '')}</span>, reported
             <span class="font-semibold text-slate-800">${escapeHtml(c.reportedOn || '—')}</span>. Revenue
             <span class="font-semibold ${revYoY > 0 ? 'text-emerald-600' : 'text-rose-600'}">${revYoY > 0 ? '+' : ''}${revYoY.toFixed(1)}%</span> year on year.
           </div>`
        : ''
    }`,
    groups,
  });
}

/** Open by ticker — used by the scatter and the calendar strip. */
export function openEarningsDrillByTicker(rows, ticker) {
  const hit = rows.find((s) => s.company?.ticker === ticker);
  if (hit) openEarningsDrill(hit);
  return !!hit;
}
