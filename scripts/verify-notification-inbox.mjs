import assert from 'node:assert/strict';
import { createInbox, STORAGE_KEY } from '../public/js/core/notification-inbox.js';
let at = 1000;
const disk = new Map();
const storage = { getItem: key => disk.get(key), setItem: (key, value) => disk.set(key, value) };
const options = { storage: () => storage, now: () => at++ };
const inbox = createInbox(options);
inbox.suppress(['backlog']);
assert.equal(inbox.push({ key: 'backlog', title: 'Old capture' }), false);
assert(inbox.push({ key: 'first', title: 'New result', href: '#/research/earnings-hub', at: '2026-09-15T12:00:00Z' }));
assert.equal(inbox.push({ key: 'first', title: 'Same result' }), false);
assert.equal(inbox.items()[0].at, Date.parse('2026-09-15T12:00:00Z'));
assert.equal(inbox.items()[0].readAt, null);
inbox.push({ key: 'unsafe', title: '<script>content</script>', href: 'javascript:alert(1)', image: 'data:image/png;base64,no', at: 1e40 });
assert.equal(inbox.items()[0].href, null); assert.equal(inbox.items()[0].image, null);
assert.doesNotThrow(() => new Date(inbox.items()[0].at).toISOString());
inbox.flush();
const secondTab = createInbox(options);
inbox.read(['first']); inbox.flush(); secondTab.sync();
assert(secondTab.items().find(row => row.id === 'first').readAt != null);
secondTab.dismiss('first'); secondTab.flush(); inbox.sync();
assert(!inbox.items().some(row => row.id === 'first'));
assert.equal(inbox.push({ key: 'first', title: 'A dismissed event cannot return' }), false);
assert(!disk.get(STORAGE_KEY).includes('New result'), 'dismissal keeps a receipt without retaining the message');
for (let i = 0; i < 120; i++) inbox.push({ key: `arrival-${i}`, title: `Arrival ${i}` });
inbox.flush();
assert.equal(createInbox(options).items().length, 121, 'arrivals survive reload without a visible-card retention cap');
inbox.push({ key: 'research:opaque-id:2', kind: 'research', title: 'Research answer ready', detail: 'PRIVATE PORTFOLIO QUESTION', href: '#/research/ask-research?session=PRIVATE_LINK' });
inbox.flush();
assert(inbox.items().some(row => row.kind === 'research'), 'research completion remains visible during this visit');
assert(!/PRIVATE PORTFOLIO|PRIVATE_LINK|Research answer ready/.test(disk.get(STORAGE_KEY)), 'private research content and links never enter device storage');
assert(!createInbox(options).items().some(row => row.kind === 'research'), 'a reload cannot expose a prior private research notification');
inbox.clearPrivate(); inbox.flush();
assert(!inbox.items().some(row => row.kind === 'research'), 'host-session changes can clear private in-memory content');
assert(inbox.items().some(row => row.id === 'arrival-0'), 'private cleanup keeps public source notifications');
const blocked = createInbox({ storage: () => { throw new Error('blocked'); }, now: () => 1000 });
blocked.push({ key: 'offline', title: 'Still readable' }); blocked.flush();
assert.equal(blocked.items().length, 1); assert.equal(blocked.saved(), false);
inbox.flush(); secondTab.flush();
// A storage event can describe a write that another tab has already superseded. Keep that
// event's records too, then reconcile to a stable snapshot without endless cross-tab writes.
const raced = createInbox(options);
const eventValue = JSON.stringify({ version: 1, items: [{ id: 'racing-arrival', title: 'Concurrent arrival', at: 1000 }] });
raced.sync(eventValue); raced.flush();
assert(createInbox(options).items().some(row => row.id === 'racing-arrival'));
const settled = disk.get(STORAGE_KEY);
raced.sync(settled); raced.flush();
assert.equal(disk.get(STORAGE_KEY), settled, 'reconciliation has a stable serialized result');
console.log('PASS notification inbox: arrival dedupe, read/dismiss persistence, cross-tab receipts, all unread retained, safe links/dates, private research isolation and unavailable storage');
