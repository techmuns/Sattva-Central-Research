// Real dashboard, browser storage and keyboard interaction; all traffic stays local.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createServer } from 'node:http';
import { resolve, extname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
const { chromium } = await import(`${process.env.PLAYWRIGHT_ROOT}/index.mjs`);
const root = resolve(fileURLToPath(new URL('../public/', import.meta.url)));
const server = createServer((req, res) => {
  const path = new URL(req.url, 'http://localhost').pathname;
  if (path.startsWith('/api/')) { res.writeHead(503, { 'content-type': 'application/json' }).end('{"ok":false}'); return; }
  const file = resolve(root, `.${path === '/' ? '/index.html' : path}`);
  if (!file.startsWith(root + sep)) { res.writeHead(404).end(); return; }
  try { res.setHeader('content-type', ({ '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png' })[extname(file)] || 'text/html'); res.end(readFileSync(file)); }
  catch { res.writeHead(404).end(); }
});
await new Promise(done => server.listen(0, '127.0.0.1', done));
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, serviceWorkers: 'block' });
  await context.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.abort());
  const page = await context.newPage(); page.setDefaultTimeout(15000);
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${base}/#/research/insider-trades?scope=portfolio`);
  const bell = () => page.locator('[data-notification-bell]');
  const panel = () => page.getByRole('dialog', { name: 'Notifications', exact: true });
  const push = value => page.evaluate(async value => (await import('/js/ui/notifications.js')).push(value), value);
  await bell().waitFor(); assert.equal(await bell().count(), 1);
  assert(await bell().evaluate(node => !!node.closest('[data-app-header]')));
  assert.equal(await page.locator('[data-notification-dot]').isVisible(), false);
  await bell().click(); assert(await panel().isVisible());
  assert.match(await panel().evaluate(node => getComputedStyle(node).backgroundColor), /^rgb\(/, 'the light inbox is opaque over dashboard content');
  assert(await page.getByText('You’re all caught up.').isVisible());
  await page.keyboard.press('Escape'); assert.equal(await panel().isVisible(), false);
  assert(await bell().evaluate(node => node === document.activeElement));
  await push({ key: 'result:1', kind: 'earnings', title: 'A new result is available', detail: 'Revenue and profit figures are ready to read.', href: '#/research/earnings-hub/latest-results', at: Date.now() });
  await push({ key: 'concall:1', kind: 'concall', title: 'Con-call analysis is ready', detail: 'Open the company’s latest call.', at: Date.now() });
  assert.equal(await push({ key: 'concall:1', title: 'Repeated event' }), false);
  assert(await page.locator('[data-notification-dot]').isVisible());
  assert.equal(await bell().getAttribute('aria-label'), 'Notifications, 2 unread');
  assert.equal(await panel().isVisible(), false, 'arrivals never open a popup');
  await bell().click(); assert.equal(await page.locator('[data-notification]').count(), 2);
  assert.equal(await bell().getAttribute('aria-label'), 'Notifications, 2 unread', 'opening alone does not mark unseen items read');
  await page.getByRole('button', { name: 'Mark as read: Con-call analysis is ready', exact: true }).click();
  assert.equal(await bell().getAttribute('aria-label'), 'Notifications, 1 unread');
  assert.equal(await page.locator('[data-notification-id="concall:1"]').getAttribute('data-read'), 'true');
  assert(await panel().isVisible(), 'reading one item keeps the list open');
  await page.getByRole('button', { name: 'Mark all as read', exact: true }).click();
  assert.equal(await page.locator('[data-notification-dot]').isVisible(), false);
  await push({ key: 'news:1', kind: 'news', title: 'A new market story', detail: 'The original source is available.', href: 'https://example.test/story', at: Date.now() });
  assert(await page.locator('[data-notification-dot]').isVisible(), 'arrivals remain unread even while the inbox is open');
  await page.screenshot({ path: '/tmp/sattva-notifications-desktop.png' });
  await page.keyboard.press('Escape');
  await page.reload(); await bell().waitFor();
  assert.equal(await bell().getAttribute('aria-label'), 'Notifications, 1 unread');
  assert.equal(await panel().isVisible(), false);
  const peer = await context.newPage();
  await peer.goto(`${base}/#/research/insider-trades?scope=portfolio`);
  await peer.locator('[data-notification-bell]').click();
  await peer.getByRole('button', { name: 'Mark all as read', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('[data-notification-bell]').getAttribute('aria-label') === 'Notifications');
  assert.equal(await panel().isVisible(), false, 'reading in another tab updates the dot without opening the inbox');
  await peer.close();
  await bell().click();
  await page.getByRole('button', { name: 'Dismiss: A new market story', exact: true }).click();
  assert.equal(await page.locator('[data-notification-dot]').isVisible(), false);
  await page.reload(); await bell().waitFor();
  assert.equal(await push({ key: 'news:1', title: 'Dismissed story' }), false, 'dismissal survives reload and repeated source arrivals');
  await bell().click();
  await page.getByRole('link', { name: 'A new result is available', exact: true }).click();
  assert(page.url().includes('earnings-hub')); assert.equal(await panel().isVisible(), false);
  await page.evaluate(() => { location.hash = '#/research/insider-trades?scope=portfolio'; });
  for (let i = 0; i < 35; i++) await push({ key: `batch:${i}`, kind: 'news', title: `Retained notification ${i}`, detail: 'A retained update stays available until dismissed.', at: Date.now() + i });
  await bell().click();
  assert.equal(await page.locator('[data-notification]').count(), 30, 'render window does not discard retained notifications');
  await page.getByRole('button', { name: 'Show older updates', exact: true }).click();
  assert.equal(await page.locator('[data-notification]').count(), 37);
  const list = page.locator('[data-notification-list]');
  await list.evaluate(node => node.scrollTop = 300);
  const anchored = await page.evaluate(() => { const list = document.querySelector('[data-notification-list]'); return [...document.querySelectorAll('[data-notification]')].find(row => row.getBoundingClientRect().bottom > list.getBoundingClientRect().top).dataset.notificationId; });
  const before = await page.locator(`[data-notification-id="${anchored}"]`).boundingBox();
  await push({ key: 'while-reading', title: 'A later arrival' });
  const after = await page.locator(`[data-notification-id="${anchored}"]`).boundingBox();
  assert(Math.abs(before.y - after.y) < 2, 'new arrivals preserve the currently read position');
  await page.keyboard.press('Escape');
  await page.evaluate(() => window.sattvaTheme.toggle()); await bell().click();
  assert.equal(await list.evaluate(node => node.scrollTop), 0, 'reopening starts with the latest notifications');
  await page.screenshot({ path: '/tmp/sattva-notifications-dark.png' });
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 }); await bell().click();
  const bounds = await panel().boundingBox();
  assert(bounds.x >= 0 && bounds.x + bounds.width <= 391 && bounds.y + bounds.height <= 845);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  assert((await bell().boundingBox()).height >= 44);
  await page.screenshot({ path: '/tmp/sattva-notifications-mobile.png' });
  await page.getByRole('button', { name: 'Close notifications', exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await bell().focus(); await page.keyboard.press('Enter'); assert(await panel().isVisible());
  await page.locator('[data-brand-mark]').click(); assert.equal(await panel().isVisible(), false, 'outside click closes the inbox');
  await push({ key: 'private-research', kind: 'research', title: 'Research answer ready', detail: 'PRIVATE TEST QUESTION', href: '#/research/ask-research?session=private-test' });
  await page.evaluate(() => dispatchEvent(new PageTransitionEvent('pagehide')));
  assert.equal(await page.evaluate(() => /PRIVATE TEST QUESTION|private-test/.test(localStorage.getItem('sattva:notification-inbox:v1'))), false);
  assert.deepEqual(errors, []);
  console.log('PASS notification bell: quiet arrivals, read/dismiss/reload, no expiry, retained paging, reader position, source links, keyboard, dark/mobile and private research isolation');
} finally { await browser.close(); server.close(); }
